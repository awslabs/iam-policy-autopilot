/// Concatenate all Python files for a handler into a single source string.
fn concatenate_source_files(files: &[PathBuf]) -> String {
    let mut combined = String::new();
    for f in files {
        if let Ok(content) = fs::read_to_string(f) {
            combined.push_str(&format!("# --- {} ---\n", f.display()));
            combined.push_str(&content);
            combined.push('\n');
        }
    }
    combined
}

/// Generate an IAM policy using an LLM (Bedrock) for a handler's source code.
async fn generate_llm_policy(
    bedrock: &BedrockClient,
    aa: &AaClient,
    catalogue: &ServiceCatalogue,
    source_files: &[PathBuf],
    model_id: &str,
    strategy: ResourcePromptStrategy,
    cdk_code: Option<&str>,
) -> Option<Vec<Value>> {
    let source_code = concatenate_source_files(source_files);
    if source_code.is_empty() {
        return None;
    }

    // Use a temp file path for the API (it reads the file)
    let temp_path = std::env::temp_dir().join("realworld_llm_source.py");
    if let Err(e) = fs::write(&temp_path, &source_code) {
        warn!("Failed to write temp source file: {}", e);
        return None;
    }

    // Write CDK code to temp file if provided
    let cdk_temp_path = cdk_code.map(|code| {
        let p = std::env::temp_dir().join("realworld_llm_cdk.ts");
        let _ = fs::write(&p, code);
        p
    });

    let outcome = generate_llm_policy_for_language(
        bedrock,
        aa,
        catalogue,
        "python",
        &temp_path,
        model_id,
        vec![],   // no prior messages
        cdk_temp_path.as_deref(),
        0,        // minimal_concrete_actions (not used for generation)
        0,        // managed_policy_concrete_actions (not used for generation)
        strategy,
    )
    .await;

    if outcome.policy_generated {
        if let Some(doc) = outcome.policy_document {
            return Some(vec![doc]);
        }
    }
    None
}

