//! `realworld-evaluator` — evaluate IPA against real-world deployed application policies.
//!
//! For each handler in a deployed application:
//!   1. Load the deployed IAM policies (inline + attached managed) as ground truth
//!   2. Run IPA (`iam-policy-autopilot`) against the handler source code
//!   3. Expand all policies into concrete IAM actions using the service catalogue
//!   4. Compute overpermissioning metrics (CDK vs IPA, CDK vs minimal)
//!   5. Write a JSON report

