#[tokio::main]
async fn main() -> Result<()> {
    tracing_subscriber::registry()
        .with(fmt::layer())
        .with(EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")))
        .init();

    let cli = Cli::parse();

    // Bootstrap: AWS clients, service catalogue, managed policies, index
    info!("Bootstrapping...");
    let aws_cfg = aws_config::defaults(BehaviorVersion::latest())
        .region(aws_config::Region::new(cli.region.clone()))
        .load()
        .await;
    let iam = IamClient::new(&aws_cfg);
    let bedrock = BedrockClient::new(&aws_cfg);
    let aa = AaClient::new(&aws_cfg);

    let mode = cli.mode.to_lowercase();
    let mode_label = if mode == "llm" { "LLM" } else { "IPA" };
    info!("Policy generation mode: {}", mode_label);

    let resource_strategy = if mode == "llm" {
        let s = ResourcePromptStrategy::from_str_loose(&cli.resource_strategy)
            .unwrap_or_else(|| {
                warn!("Unknown resource strategy '{}', defaulting to resource-star", cli.resource_strategy);
                ResourcePromptStrategy::ResourceStar
            });
        info!("Resource prompt strategy: {}", s);
        s
    } else {
        ResourcePromptStrategy::ResourceStar // unused in IPA mode
    };

    let account = match &cli.account {
        Some(a) => a.clone(),
        None => iac_runner::get_aws_account_id(&aws_sdk_sts::Client::new(&aws_cfg)).await?,
    };
    info!("Account: {}, Region: {}", account, cli.region);

    fs::create_dir_all(&cli.cache_dir)?;
    let catalogue = load_or_fetch_catalogue(&cli.cache_dir.join("service_catalogue.json")).await?;
    info!("Service catalogue: {} services", catalogue.len());

    let mp_cache_path = cli.cache_dir.join("managed_policy_cache.json");
    let managed_policies = load_or_fetch_managed_policies(&iam, &mp_cache_path).await?;
    info!("Managed policies: {}", managed_policies.len());

    let index_path = cli.cache_dir.join("policy_index.json");
    let index = load_or_build_index(&index_path, &mp_cache_path, &managed_policies, &catalogue)?;
    info!("Policy index loaded");

    // Discover handlers
    let filter: Option<HashSet<String>> = cli.only.as_ref().map(|s| {
        s.split(',').map(|h| h.trim().to_string()).collect()
    });

    let mut handler_dirs: Vec<(String, PathBuf)> = Vec::new();
    for entry in fs::read_dir(&cli.handlers_dir)? {
        let entry = entry?;
        if !entry.file_type()?.is_dir() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_string();
        let deployed_dir = entry.path().join("deployed_policy");
        if !deployed_dir.exists() {
            continue; // no deployed policy = not in scope
        }
        if let Some(ref f) = filter {
            if !f.contains(&name) {
                continue;
            }
        }
        handler_dirs.push((name, entry.path()));
    }
    handler_dirs.sort_by(|a, b| a.0.cmp(&b.0));
    info!("Found {} handlers with deployed policies", handler_dirs.len());

    fs::create_dir_all(&cli.output_dir)?;

    // Process each handler
    let mut results: Vec<HandlerResult> = Vec::new();

    for (handler_name, handler_dir) in &handler_dirs {
        info!("=== {} ===", handler_name);
        let deployed_dir = handler_dir.join("deployed_policy");
        let handler_source_dir = handler_dir.join("handler");

        // 1. Load deployed policies (ground truth)
        let inline_docs = load_inline_policies(&deployed_dir)
            .with_context(|| format!("Failed to load inline policies for {}", handler_name))?;
        let attached_arns = load_attached_policy_arns(&deployed_dir)?;

        let cdk_inline_actions = count_concrete_actions_from_policies(&inline_docs, &catalogue);
        let managed_actions = expand_managed_policy_arns(&attached_arns, &index, &catalogue);
        let cdk_all_actions: HashSet<String> = cdk_inline_actions
            .union(&managed_actions)
            .cloned()
            .collect();

        info!(
            "  CDK: {} inline actions, {} managed actions, {} total",
            cdk_inline_actions.len(),
            managed_actions.len(),
            cdk_all_actions.len()
        );

        // 2. Generate policy (IPA or LLM mode)
        let policy_suffix = if mode == "llm" { "llm" } else { "ipa" };
        let policy_output_path = cli.output_dir.join(format!("{}_{}_policy.json", handler_name, policy_suffix));
        let mut files_analyzed: u32 = 0;
        let mut lines_analyzed: u32 = 0;
        let mut ipa_generation_time: f64 = 0.0;
        let generated_policies: Option<Vec<Value>> = if cli.skip_ipa && policy_output_path.exists() {
            info!("  Loading cached {} policy from {:?}", mode_label, policy_output_path);
            let content = fs::read_to_string(&policy_output_path)?;
            Some(serde_json::from_str(&content)?)
        } else if handler_source_dir.exists() {
            // Collect handler Python files
            let mut all_files: Vec<PathBuf> = Vec::new();
            for entry in walkdir::WalkDir::new(&handler_source_dir)
                .into_iter()
                .filter_map(|e| e.ok())
            {
                if entry.path().extension().map_or(false, |ext| ext == "py") {
                    all_files.push(entry.path().to_path_buf());
                }
            }

            // If handler uses shared layer, trace imports and add reachable files
            if uses_shared_layer(handler_dir) {
                if let Some(shared_dir) = &cli.shared_layer_dir {
                    let reachable = trace_reachable_shared_files(
                        &handler_source_dir,
                        shared_dir,
                        &cli.shared_package,
                    );
                    if !reachable.is_empty() {
                        info!(
                            "  Import tracing: {} reachable shared modules",
                            reachable.len()
                        );
                        all_files.extend(reachable);
                    } else {
                        warn!("  Import tracing found no shared modules");
                    }
                } else {
                    warn!("  Handler uses shared layer but --shared-layer-dir not provided");
                }
            }

            if all_files.is_empty() {
                warn!("  No Python files found for {}", handler_name);
                None
            } else {
                files_analyzed = all_files.len() as u32;
                lines_analyzed = count_lines(&all_files);
                info!("  Running {} on {} files ({} lines)", mode_label, files_analyzed, lines_analyzed);
                let start = std::time::Instant::now();

                let policies = if mode == "llm" {
                    let model_id = cli.bedrock_model_id.clone()
                        .unwrap_or_else(|| default_bedrock_model_id(&cli.region, &account));
                    info!("  Using Bedrock model: {}", model_id);

                    // Load CDK construct code if --cdk-lib-dir is provided
                    let cdk_code = cli.cdk_lib_dir.as_ref().and_then(|cdk_dir| {
                        get_cdk_construct_path(handler_name).and_then(|rel_path| {
                            let full_path = cdk_dir.join(rel_path);
                            match fs::read_to_string(&full_path) {
                                Ok(code) => {
                                    info!("  CDK context: {} ({} chars)", rel_path, code.len());
                                    Some(code)
                                }
                                Err(e) => {
                                    warn!("  CDK context not found at {:?}: {}", full_path, e);
                                    None
                                }
                            }
                        })
                    });

                    let n_reps = cli.llm_repetitions.max(1);
                    let mut trials: Vec<(usize, Vec<Value>, u32)> = Vec::new(); // (trial_idx, policies, concrete_count)

                    for trial_idx in 1..=n_reps {
                        if n_reps > 1 {
                            info!("  Trial {}/{} ...", trial_idx, n_reps);
                        }
                        let trial_policies = generate_llm_policy(
                            &bedrock, &aa, &catalogue, &all_files, &model_id,
                            resource_strategy, cdk_code.as_deref(),
                        ).await;

                        if let Some(ref p) = trial_policies {
                            let concrete = count_concrete_actions_from_policies(p, &catalogue);
                            let trial_path = if n_reps > 1 {
                                cli.output_dir.join(format!("{}_{}_policy_trial_{:02}.json", handler_name, policy_suffix, trial_idx))
                            } else {
                                policy_output_path.clone()
                            };
                            let json = serde_json::to_string_pretty(p)?;
                            fs::write(&trial_path, &json)?;
                            trials.push((trial_idx, p.clone(), concrete.len() as u32));
                            if n_reps > 1 {
                                info!("  Trial {}: {} concrete actions", trial_idx, concrete.len());
                            }
                        } else if n_reps > 1 {
                            warn!("  Trial {}: LLM generation failed", trial_idx);
                        }
                    }

                    if trials.is_empty() {
                        None
                    } else {
                        // Pick median trial by concrete action count
                        trials.sort_by_key(|t| t.2);
                        let median = &trials[trials.len() / 2];
                        if n_reps > 1 {
                            info!("  Median trial: {} ({} concrete actions)", median.0, median.2);
                        }
                        // Save the median as the representative policy
                        let json = serde_json::to_string_pretty(&median.1)?;
                        fs::write(&policy_output_path, &json)?;
                        Some(median.1.clone())
                    }
                } else {
                    generate_policies_multi(
                        &all_files,
                        &cli.autopilot_binary,
                        &cli.region,
                        &account,
                    )
                };

                ipa_generation_time = start.elapsed().as_secs_f64();
                info!("  {} generation took {:.1}s", mode_label, ipa_generation_time);
                if let Some(ref p) = policies {
                    let json = serde_json::to_string_pretty(p)?;
                    fs::write(&policy_output_path, &json)?;
                }
                policies
            }
        } else {
            warn!("  No handler source directory found at {:?}", handler_source_dir);
            None
        };

        // 3. Compute metrics
        match generated_policies {
            Some(policies) => {
                let gen_actions = count_concrete_actions_from_policies(&policies, &catalogue);
                info!(
                    "  {}: {} concrete actions",
                    mode_label, gen_actions.len()
                );
                let result = evaluate_handler(
                    handler_name,
                    files_analyzed,
                    lines_analyzed,
                    ipa_generation_time,
                    &cdk_all_actions,
                    &cdk_inline_actions,
                    &gen_actions,
                );
                info!(
                    "  CDK overperm ratio: {:.2}",
                    result.cdk_overpermission_ratio_vs_ipa
                );
                results.push(result);
            }
            None => {
                warn!("  {} failed for {}", mode_label, handler_name);
                results.push(HandlerResult {
                    handler: handler_name.clone(),
                    files_analyzed,
                    lines_analyzed,
                    ipa_generation_time_seconds: ipa_generation_time,
                    cdk_concrete_action_count: cdk_all_actions.len() as u32,
                    cdk_inline_concrete_action_count: cdk_inline_actions.len() as u32,
                    ipa_concrete_action_count: 0,
                    cdk_overpermission_ratio_vs_ipa: 0.0,
                    ipa_success: false,
                });
            }
        }
    }

    // 4. Build summary
    let successful: Vec<&HandlerResult> = results.iter().filter(|r| r.ipa_success).collect();
    let summary = EvaluationSummary {
        total_handlers: results.len(),
        ipa_success_count: successful.len(),
        avg_cdk_overpermission_ratio: if successful.is_empty() {
            0.0
        } else {
            successful
                .iter()
                .map(|r| r.cdk_overpermission_ratio_vs_ipa)
                .sum::<f64>()
                / successful.len() as f64
        },
    };

    let report = EvaluationReport {
        handlers: results,
        summary,
    };

    // 5. Write report
    let report_path = cli.output_dir.join("evaluation_report.json");
    let json = serde_json::to_string_pretty(&report)?;
    fs::write(&report_path, &json)?;
    info!("Report written to {:?}", report_path);

    // Print summary
    println!("\n=== Real-World App Evaluation Summary ===");
    println!(
        "Handlers: {}/{} succeeded",
        report.summary.ipa_success_count, report.summary.total_handlers
    );
    println!(
        "Avg CDK overpermission ratio: {:.2}x",
        report.summary.avg_cdk_overpermission_ratio
    );

    Ok(())
}
