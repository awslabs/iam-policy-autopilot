/// Count total lines in a set of files.
fn count_lines(files: &[PathBuf]) -> u32 {
    files
        .iter()
        .filter_map(|f| fs::read_to_string(f).ok())
        .map(|content| content.lines().count() as u32)
        .sum()
}

fn evaluate_handler(
    handler_name: &str,
    files_analyzed: u32,
    lines_analyzed: u32,
    ipa_generation_time_seconds: f64,
    cdk_actions: &HashSet<String>,
    cdk_inline_actions: &HashSet<String>,
    ipa_actions: &HashSet<String>,
) -> HandlerResult {
    let cdk_overpermission_ratio = cdk_actions.len() as f64 / ipa_actions.len().max(1) as f64;

    HandlerResult {
        handler: handler_name.to_string(),
        files_analyzed,
        lines_analyzed,
        ipa_generation_time_seconds,
        cdk_concrete_action_count: cdk_actions.len() as u32,
        cdk_inline_concrete_action_count: cdk_inline_actions.len() as u32,
        ipa_concrete_action_count: ipa_actions.len() as u32,
        cdk_overpermission_ratio_vs_ipa: cdk_overpermission_ratio,
        ipa_success: true,
    }
}

