#[derive(Debug, Serialize, Deserialize)]
struct HandlerResult {
    handler: String,
    /// Total Python files analyzed by IPA (handler + traced shared layer).
    files_analyzed: u32,
    /// Total lines of Python analyzed by IPA.
    lines_analyzed: u32,
    /// Concrete actions granted by the deployed CDK policies (inline + managed).
    cdk_concrete_action_count: u32,
    /// Concrete actions granted by the deployed inline policies only.
    cdk_inline_concrete_action_count: u32,
    /// Concrete actions generated by IPA.
    ipa_concrete_action_count: u32,
    /// IPA policy generation time in seconds.
    ipa_generation_time_seconds: f64,
    /// Overpermission ratio: CDK concrete actions / IPA concrete actions.
    /// >1 means CDK is more permissive than IPA.
    cdk_overpermission_ratio_vs_ipa: f64,
    /// IPA policy generation succeeded.
    ipa_success: bool,
}

#[derive(Debug, Serialize, Deserialize)]
struct EvaluationReport {
    handlers: Vec<HandlerResult>,
    summary: EvaluationSummary,
}

#[derive(Debug, Serialize, Deserialize)]
struct EvaluationSummary {
    total_handlers: usize,
    ipa_success_count: usize,
    avg_cdk_overpermission_ratio: f64,
}

