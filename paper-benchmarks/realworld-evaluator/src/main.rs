#[derive(Debug, Parser)]
#[command(
    name = "realworld-evaluator",
    about = "Evaluate IPA against real-world deployed application IAM policies."
)]
struct Cli {
    /// Path to the handlers directory (e.g. examples/real-world-apps/genai-chatbot/handlers).
    /// Each subdirectory should contain:
    ///   - handler/          (Python source code)
    ///   - deployed_policy/  (inline_*.json + attached_policies.json)
    #[arg(long)]
    handlers_dir: PathBuf,

    /// Path to the shared layer directory (e.g. genai-chatbot/shared_layer/genai_core).
    /// Used to resolve handler imports into the shared layer.
    #[arg(long)]
    shared_layer_dir: Option<PathBuf>,

    /// Shared package name (default: genai_core).
    #[arg(long, default_value = "genai_core")]
    shared_package: String,

    /// Path to the iam-policy-autopilot binary.
    #[arg(long, default_value = "iam-policy-autopilot")]
    autopilot_binary: String,

    /// AWS region.
    #[arg(long, default_value = "us-east-1")]
    region: String,

    /// AWS account ID (auto-detected if not provided).
    #[arg(long)]
    account: Option<String>,

    /// Directory for caching service catalogue and managed policies.
    #[arg(long, default_value = ".cache")]
    cache_dir: PathBuf,

    /// Output directory for the evaluation report.
    #[arg(long, default_value = "realworld_results")]
    output_dir: PathBuf,

    /// Only evaluate these handlers (comma-separated). If omitted, all handlers are evaluated.
    #[arg(long)]
    only: Option<String>,

    /// Skip IPA generation (use previously generated policies from output_dir).
    #[arg(long)]
    skip_ipa: bool,

    /// Policy generation mode: "ipa" (default) or "llm".
    /// In LLM mode, uses Bedrock to generate policies instead of IPA.
    #[arg(long, default_value = "ipa")]
    mode: String,

    /// Bedrock model ID for LLM mode (default: auto-detected based on region).
    #[arg(long)]
    bedrock_model_id: Option<String>,

    /// Resource prompt strategy for LLM mode: "bare", "wildcards", or "resource-star".
    #[arg(long, default_value = "resource-star")]
    resource_strategy: String,

    /// Path to the CDK lib directory for CDK-context LLM prompts.
    /// When provided in LLM mode, the relevant CDK construct file is included in the prompt.
    #[arg(long)]
    cdk_lib_dir: Option<PathBuf>,

    /// Number of LLM repetitions per handler (default: 1).
    /// When > 1, the median trial (by concrete action count) is used as the representative.
    #[arg(long, default_value_t = 1)]
    llm_repetitions: usize,
}

