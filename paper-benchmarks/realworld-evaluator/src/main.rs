/// Load all inline policy documents from a handler's deployed_policy/ directory.
fn load_inline_policies(deployed_dir: &Path) -> Result<Vec<Value>> {
    let mut docs = Vec::new();
    for entry in fs::read_dir(deployed_dir)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().to_string();
        if name.starts_with("inline_") && name.ends_with(".json") {
            let content = fs::read_to_string(entry.path())?;
            let raw: Value = serde_json::from_str(&content)?;
            // The inline policy JSON from `aws iam get-role-policy` wraps the
            // document under "PolicyDocument".
            if let Some(doc) = raw.get("PolicyDocument") {
                docs.push(doc.clone());
            } else {
                docs.push(raw);
            }
        }
    }
    Ok(docs)
}

/// Load attached managed policy ARNs from attached_policies.json.
fn load_attached_policy_arns(deployed_dir: &Path) -> Result<Vec<String>> {
    let path = deployed_dir.join("attached_policies.json");
    if !path.exists() {
        return Ok(vec![]);
    }
    let content = fs::read_to_string(&path)?;
    let entries: Vec<Value> = serde_json::from_str(&content)?;
    Ok(entries
        .iter()
        .filter_map(|e| e.get("PolicyArn").and_then(|v| v.as_str()).map(String::from))
        .collect())
}

/// Expand managed policy ARNs into concrete actions using the policy index.
fn expand_managed_policy_arns(
    arns: &[String],
    index: &iac_benchmarker::policy_index::PolicyIndex,
    catalogue: &ServiceCatalogue,
) -> HashSet<String> {
    let mut concrete = HashSet::new();
    for arn in arns {
        if let Some(patterns) = index.policy_arn_to_allow_patterns.get(arn) {
            for pattern in patterns {
                let prefix = match pattern.find(':') {
                    Some(pos) => pattern[..pos].to_lowercase(),
                    None => continue,
                };
                if let Some(actions) = catalogue.get(&prefix) {
                    for action in actions {
                        let c = format!("{}:{}", prefix, action);
                        if action_covered_by(pattern, &c) {
                            concrete.insert(c);
                        }
                    }
                }
            }
        } else {
            warn!("Managed policy ARN not found in index: {}", arn);
        }
    }
    concrete
}

