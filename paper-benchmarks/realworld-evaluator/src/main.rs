use regex::Regex;
use std::collections::VecDeque;

/// Extract imported module names from a Python source file using regex.
/// Handles `import foo.bar` and `from foo.bar import baz`.
fn find_imports(filepath: &Path) -> Vec<String> {
    let content = match fs::read_to_string(filepath) {
        Ok(c) => c,
        Err(e) => {
            warn!("Failed to read {}: {}", filepath.display(), e);
            return vec![];
        }
    };

    let import_re = Regex::new(r"(?m)^\s*import\s+([\w.]+)").unwrap();
    let from_re = Regex::new(r"(?m)^\s*from\s+([\w.]+)\s+import").unwrap();

    let mut modules = Vec::new();
    for cap in import_re.captures_iter(&content) {
        modules.push(cap[1].to_string());
    }
    for cap in from_re.captures_iter(&content) {
        modules.push(cap[1].to_string());
    }
    modules
}

/// Resolve a module name like `genai_core.documents` to actual .py files
/// in the shared layer directory.
fn resolve_module_to_files(
    module_name: &str,
    shared_layer_dir: &Path,
    shared_package: &str,
) -> Vec<PathBuf> {
    if !module_name.starts_with(shared_package) {
        return vec![];
    }

    let relative = &module_name[shared_package.len()..];
    let relative = relative.strip_prefix('.').unwrap_or(relative);

    let mut base_path = shared_layer_dir.to_path_buf();
    if !relative.is_empty() {
        for part in relative.split('.') {
            base_path = base_path.join(part);
        }
    }

    let mut results = Vec::new();

    // Could be a file: genai_core/documents.py
    let py_file = base_path.with_extension("py");
    if py_file.exists() {
        results.push(py_file);
    }

    // Could be a package: genai_core/aurora/__init__.py
    let init_file = base_path.join("__init__.py");
    if init_file.exists() {
        results.push(init_file);
        // Include all .py files in the package directory
        if let Ok(entries) = fs::read_dir(&base_path) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().map_or(false, |e| e == "py") && !results.contains(&path) {
                    results.push(path);
                }
            }
        }
    }

    results
}

/// BFS from handler files through shared layer imports, returning all
/// reachable shared layer .py files.
fn trace_reachable_shared_files(
    handler_source_dir: &Path,
    shared_layer_dir: &Path,
    shared_package: &str,
) -> Vec<PathBuf> {
    // Collect handler .py files
    let handler_files: Vec<PathBuf> = walkdir::WalkDir::new(handler_source_dir)
        .into_iter()
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().map_or(false, |ext| ext == "py"))
        .map(|e| e.path().to_path_buf())
        .collect();

    let mut visited_files: HashSet<PathBuf> = HashSet::new();
    let mut visited_modules: HashSet<String> = HashSet::new();
    let mut reachable: Vec<PathBuf> = Vec::new();
    let mut queue: VecDeque<PathBuf> = handler_files.into_iter().collect();

    while let Some(current) = queue.pop_front() {
        if visited_files.contains(&current) {
            continue;
        }
        visited_files.insert(current.clone());

        for module_name in find_imports(&current) {
            // Trace sub-prefixes: genai_core.aurora.delete -> genai_core.aurora -> genai_core
            let parts: Vec<&str> = module_name.split('.').collect();
            for i in 1..=parts.len() {
                let prefix = parts[..i].join(".");
                if visited_modules.contains(&prefix) {
                    continue;
                }
                visited_modules.insert(prefix.clone());

                let resolved = resolve_module_to_files(&prefix, shared_layer_dir, shared_package);
                if resolved.is_empty() && prefix.starts_with(shared_package) && prefix != shared_package {
                    warn!(
                        "Unresolved shared layer import: {} (from {})",
                        prefix,
                        current.display()
                    );
                }
                for file in resolved {
                    if !visited_files.contains(&file) {
                        reachable.push(file.clone());
                        queue.push_back(file);
                    }
                }
            }
        }
    }

    reachable
}

/// Check if a handler uses the shared layer (from metadata.json).
fn uses_shared_layer(handler_dir: &Path) -> bool {
    let meta_path = handler_dir.join("metadata.json");
    if !meta_path.exists() {
        return false;
    }
    match fs::read_to_string(&meta_path) {
        Ok(content) => {
            if let Ok(meta) = serde_json::from_str::<Value>(&content) {
                meta.get("uses_shared_layer")
                    .and_then(|v| v.as_bool())
                    .unwrap_or(false)
            } else {
                false
            }
        }
        Err(_) => false,
    }
}

/// Run IPA with multiple input files and return parsed policy documents.
fn generate_policies_multi(
    files: &[PathBuf],
    autopilot_binary: &str,
    region: &str,
    account: &str,
) -> Option<Vec<Value>> {
    use std::process::Command;

    let mut cmd = Command::new(autopilot_binary);
    cmd.arg("generate-policies")
        .arg("--region")
        .arg(region)
        .arg("--account")
        .arg(account)
        .arg("--pretty");
    for f in files {
        cmd.arg(f);
    }

    let file_list: Vec<String> = files.iter().map(|f| f.to_string_lossy().to_string()).collect();
    info!(
        "[autopilot] Generating IAM policies for {} files: {}",
        files.len(),
        if files.len() <= 3 {
            file_list.join(" ")
        } else {
            format!("{} ... ({} more)", file_list[..2].join(" "), files.len() - 2)
        }
    );

    match cmd.output() {
        Err(e) => {
            warn!("generate-policies exec error: {}", e);
            None
        }
        Ok(out) if !out.status.success() => {
            warn!(
                "generate-policies failed: {}",
                String::from_utf8_lossy(&out.stderr).trim()
            );
            None
        }
        Ok(out) => {
            // Parse the autopilot output: {"Policies": [{"Policy": {...}}, ...]}
            let parsed: Value = match serde_json::from_slice(&out.stdout) {
                Ok(v) => v,
                Err(e) => {
                    warn!("Failed to parse generate-policies output: {}", e);
                    return None;
                }
            };
            let policies: Vec<Value> = parsed
                .get("Policies")
                .and_then(|p| p.as_array())
                .map(|arr| {
                    arr.iter()
                        .filter_map(|item| item.get("Policy").cloned())
                        .collect()
                })
                .unwrap_or_default();
            if policies.is_empty() {
                warn!("No valid policies found in iam-policy-autopilot output");
                return None;
            }
            Some(policies)
        }
    }
}

