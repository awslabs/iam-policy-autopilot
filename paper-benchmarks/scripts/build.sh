#!/usr/bin/env bash
#
# Build the iam-policy-autopilot binary (from the repo root) and all
# paper-benchmark binaries (from the paper-benchmarks workspace).
#
# First checks that all dependencies are present:
#   - build-time deps (cargo, cmake, a C/C++ compiler) — missing any aborts the build;
#   - runtime deps for running the benchmarks (AWS CLI, Node/CDK, jq, and the
#     per-language toolchains) — missing any only warns, since you can still
#     build and run a subset of languages.
#
# Then ensures the four vendored git submodules (botocore, boto3, and the
# sparse Terraform/Java data files) are present. build.rs needs these to
# generate its embedded models. When the repository was cloned with
# `--recurse-submodules` this is already done and the step is a no-op. When the
# tree came from a GitHub source ZIP — which contains NO submodule contents and
# is not a git repository at all — this reconstructs a minimal git project in
# place and fetches only the pinned data each submodule needs. See
# setup_submodules() below.
#
# Usage:
#   ./paper-benchmarks/scripts/build.sh
#   SKIP_DEP_CHECK=1 ./paper-benchmarks/scripts/build.sh   # skip the preflight check
#   SKIP_SUBMODULES=1 ./paper-benchmarks/scripts/build.sh  # skip submodule setup
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BENCH_DIR="$(dirname "$SCRIPT_DIR")"          # paper-benchmarks/
REPO_ROOT="$(dirname "$BENCH_DIR")"           # repository root

# ---------------------------------------------------------------------------
# Dependency preflight
# ---------------------------------------------------------------------------

# have <cmd> [more...]: true only if every command is on PATH.
have() { for c in "$@"; do command -v "$c" >/dev/null 2>&1 || return 1; done; return 0; }

check_dependencies() {
    # Build-time: required to compile. name|purpose, command is the name.
    local build_required=(
        "cargo|Rust toolchain (build the binaries)"
        "rustc|Rust compiler"
        "cmake|build the highs LP solver"
        "cc|C compiler for native deps"
        "c++|C++ compiler for the highs LP solver"
        "git|fetch the pinned submodule data (see setup_submodules)"
        "python3|botocore xform_name map generated by build.rs"
    )
    # Runtime: needed to *run* the benchmarks, not to build. Missing => warn only.
    local runtime_optional=(
        "aws|AWS CLI (credentials / service calls)"
        "docker|Docker (CDK Lambda layer + Batch container builds)"
        "node|Node.js (CDK + TypeScript scripts)"
        "npx|run AWS CDK (npx cdk ...)"
        "jq|parse CDK outputs in deploy.sh"
        "go|Go data-plane scripts"
        "java|Java data-plane scripts"
        "mvn|Maven (build/run Java scripts)"
        "ts-node|run TypeScript data-plane scripts"
    )
    # Python packages needed for the real-world evaluation scripts.
    local python_packages=(
        "boto3|AWS SDK for Python (swap_validation.py, extract_deployed_policies.py)"
        "pydantic|data validation (integtest clients)"
        "gql|GraphQL client (handler_scenarios.py)"
        "aiohttp|async HTTP for gql transport"
    )

    local missing_build=() missing_runtime=() missing_python=()
    local entry cmd purpose pkg

    echo "==> Checking dependencies"
    for entry in "${build_required[@]}"; do
        cmd="${entry%%|*}"; purpose="${entry#*|}"
        if have "$cmd"; then
            printf "  [ok]      %-9s %s\n" "$cmd" "($purpose)"
        else
            printf "  [MISSING] %-9s %s\n" "$cmd" "($purpose)"
            missing_build+=("$cmd")
        fi
    done
    for entry in "${runtime_optional[@]}"; do
        cmd="${entry%%|*}"; purpose="${entry#*|}"
        if have "$cmd"; then
            printf "  [ok]      %-9s %s\n" "$cmd" "($purpose)"
        else
            printf "  [warn]    %-9s %s\n" "$cmd" "($purpose)"
            missing_runtime+=("$cmd")
        fi
    done
    echo

    if have python3; then
        for entry in "${python_packages[@]}"; do
            pkg="${entry%%|*}"; purpose="${entry#*|}"
            if python3 -c "import $pkg" 2>/dev/null; then
                printf "  [ok]      %-9s %s\n" "$pkg" "($purpose)"
            else
                printf "  [warn]    %-9s %s\n" "$pkg" "($purpose)"
                missing_python+=("$pkg")
            fi
        done
    fi
    echo

    if [[ ${#missing_runtime[@]} -gt 0 ]]; then
        echo "Warning: missing runtime dependencies: ${missing_runtime[*]}"
        echo "  The build will still succeed, but running the benchmarks needs these."
        echo "  A missing language toolchain makes that language's scripts fail to"
        echo "  spawn (logged as 'exit code -1'); scope a run with --language/--languages"
        echo "  or --skip-llm / --skip-iamfast. See paper-benchmarks/README.md."
        echo
    fi

    if [[ ${#missing_python[@]} -gt 0 ]]; then
        echo "Warning: missing Python packages: ${missing_python[*]}"
        echo "  Install with: pip install ${missing_python[*]}"
        echo
    fi

    if [[ ${#missing_build[@]} -gt 0 ]]; then
        echo "Error: missing build dependencies: ${missing_build[*]}" >&2
        echo "Install them and re-run, or set SKIP_DEP_CHECK=1 to bypass this check." >&2
        exit 1
    fi
}

if [[ "${SKIP_DEP_CHECK:-0}" != "1" ]]; then
    check_dependencies
fi

# ---------------------------------------------------------------------------
# Submodule setup
# ---------------------------------------------------------------------------
#
# The build depends on four git submodules under
# iam-policy-autopilot-policy-generation/resources/config/. build.rs reads a
# specific data path out of each and refuses to build if it is missing:
#
#   submodule                data path build.rs requires            checkout
#   botocore (botocore-data) botocore/data (+ the botocore package, full  (Python xform_name
#                            imported by generate_python_name_map.py)  is imported)
#   boto3                    boto3/data                              sparse
#   terraform-provider-aws   names/data/names_data.hcl               sparse
#   aws-sdk-java-v2          utils/.../CodegenNamingUtils.java        sparse
#
# The submodule commits are pinned by the superproject. A source ZIP drops that
# pin (it lives in git tree metadata, not the working tree), so the pinned SHAs
# are recorded here. To refresh them after bumping a submodule, run from a real
# clone:
#   git submodule status
# and copy the new SHAs into the table below (SHA + superproject-relative path).
GEN_ROOT="$REPO_ROOT/iam-policy-autopilot-policy-generation/resources/config"

# One row per submodule: "<pinned-sha> <path-relative-to-repo-root> <sparse-pattern-or-FULL> <data-path-relative-to-repo-root>"
# sparse-pattern FULL means a complete checkout (botocore needs its Python package importable).
SUBMODULES=(
  "3328b3d91f855d677062465c0a4f9bcd5a40cf81 iam-policy-autopilot-policy-generation/resources/config/sdks/botocore-data FULL iam-policy-autopilot-policy-generation/resources/config/sdks/botocore-data/botocore/data"
  "09cf3995c72debecb745ca17865dc3d77f1dabb2 iam-policy-autopilot-policy-generation/resources/config/sdks/boto3 /boto3/data iam-policy-autopilot-policy-generation/resources/config/sdks/boto3/boto3/data"
  "b53a72bc2e0bf0395b4b1f91e06340785ddaac86 iam-policy-autopilot-policy-generation/resources/config/terraform/terraform-provider-aws /names/data/names_data.hcl iam-policy-autopilot-policy-generation/resources/config/terraform/terraform-provider-aws/names/data/names_data.hcl"
  "708dfc16f78e8082ebb6f2ac043a3b894fe3b27e iam-policy-autopilot-policy-generation/resources/config/sdks/aws-sdk-java-v2 /utils/src/main/java/software/amazon/awssdk/utils/internal/CodegenNamingUtils.java iam-policy-autopilot-policy-generation/resources/config/sdks/aws-sdk-java-v2/utils/src/main/java/software/amazon/awssdk/utils/internal/CodegenNamingUtils.java"
)

# all_submodule_data_present: true only if every submodule's required data path exists.
all_submodule_data_present() {
    local row sha path pattern data
    for row in "${SUBMODULES[@]}"; do
        read -r sha path pattern data <<<"$row"
        [[ -e "$REPO_ROOT/$data" ]] || return 1
    done
    return 0
}

# Fetch one submodule's pinned commit into <dir>, taking only <pattern> (or a
# full checkout when pattern is FULL). Uses a blobless partial clone so a huge
# repo (terraform-provider-aws is ~300MB checked out) costs only the few files
# we actually read. Leaves a valid .git so build.rs's git2 Repository::open —
# used to embed submodule version info — still works.
fetch_submodule_data() {
    local sha="$1" dir="$2" pattern="$3"
    mkdir -p "$dir"
    git -C "$dir" init -q
    # Idempotent remote: re-runs must not fail on an existing 'origin'.
    git -C "$dir" remote remove origin 2>/dev/null || true
    git -C "$dir" remote add origin "$4"
    if [[ "$pattern" != "FULL" ]]; then
        git -C "$dir" config core.sparseCheckout true
        git -C "$dir" sparse-checkout set --no-cone "$pattern" >/dev/null
    fi
    GIT_TERMINAL_PROMPT=0 git -C "$dir" fetch --filter=blob:none --depth 1 origin "$sha" >/dev/null
    git -C "$dir" checkout -q FETCH_HEAD
}

setup_submodules() {
    if all_submodule_data_present; then
        echo "==> Submodules already present (skipping setup)"
        return 0
    fi

    # A real clone (has .git) can populate submodules the normal way, and
    # build.rs will do it on demand. Only reconstruct when the tree is a
    # non-git source ZIP.
    if git -C "$REPO_ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        echo "==> Submodule data missing but this is a git repo; initializing via git"
        git -C "$REPO_ROOT" submodule update --init --depth 1
        return 0
    fi

    echo "==> Submodule data missing and no git repo (source ZIP); reconstructing"
    if ! command -v git >/dev/null 2>&1; then
        echo "Error: git is required to fetch submodule data from a source ZIP." >&2
        echo "  Install git, or use a clone made with --recurse-submodules." >&2
        exit 1
    fi

    # Make the extracted ZIP a git project so the fetched submodules are
    # registered as proper gitlinks (build.rs opens them with git2).
    git -C "$REPO_ROOT" init -q

    # Read submodule URLs from .gitmodules, rewriting SSH remotes to HTTPS so no
    # SSH key is needed (two of the four submodules pin git@github.com: URLs).
    local gm="$REPO_ROOT/.gitmodules"
    local row sha path pattern data name url
    for row in "${SUBMODULES[@]}"; do
        read -r sha path pattern data <<<"$row"
        # Resolve this path's submodule URL from .gitmodules by matching on path.
        name="$(git config --file "$gm" --get-regexp '^submodule\..*\.path$' \
                | awk -v p="$path" '$2==p {print $1}' | sed -E 's/^submodule\.(.*)\.path$/\1/')"
        if [[ -z "$name" ]]; then
            echo "Error: no submodule entry for path '$path' in .gitmodules" >&2
            exit 1
        fi
        url="$(git config --file "$gm" "submodule.$name.url")"
        url="${url/#git@github.com:/https://github.com/}"
        url="${url/#ssh:\/\/git@github.com\//https://github.com/}"

        echo "  fetching $path @ ${sha:0:12} ($([[ "$pattern" == FULL ]] && echo full || echo "sparse: $pattern"))"
        fetch_submodule_data "$sha" "$REPO_ROOT/$path" "$pattern" "$url"

        # Register the pinned commit as a gitlink in the superproject index.
        git -C "$REPO_ROOT" update-index --add --cacheinfo 160000,"$sha","$path"
    done

    if ! all_submodule_data_present; then
        echo "Error: submodule setup finished but required data is still missing." >&2
        exit 1
    fi
    echo "==> Submodule reconstruction complete"
}

if [[ "${SKIP_SUBMODULES:-0}" != "1" ]]; then
    setup_submodules
fi

echo "==> Building iam-policy-autopilot (release) from repo root"
cargo build --release --manifest-path "$REPO_ROOT/Cargo.toml" --bin iam-policy-autopilot

echo "==> Building paper-benchmark binaries (release)"
cargo build --release --manifest-path "$BENCH_DIR/Cargo.toml"

echo
echo "Built binaries:"
echo "  IPA:                $REPO_ROOT/target/release/iam-policy-autopilot"
echo "  iac-benchmarker:    $BENCH_DIR/target/release/iac-benchmarker"
echo "  iac-paper-figures:  $BENCH_DIR/target/release/iac-paper-figures"
echo "  iac-coverage-analyzer: $BENCH_DIR/target/release/iac-coverage-analyzer"
echo "  realworld-evaluator: $BENCH_DIR/target/release/realworld-evaluator"
